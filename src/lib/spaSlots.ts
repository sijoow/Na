function message(s: Shop, date: string, time: string, extra: string[]): string {
  const ko = [
    `[${date} ${s.name} 예약용 · ${s.channel}]`,
    "안녕하세요, 예약하고 싶어요.",
    `- 날짜/시간: ${date} ${time}`,
    "- 이름: ○○○ (영문)",
    `- 인원·코스: 성인 2명 ${s.adult} / 아이 1명(만 4세, 키 ○○cm) ${s.kids}`,
    `- 방: ${s.room}`,
    ...extra,
    "최종 금액(팁 포함 여부)과 결제 방법 알려 주세요. 감사합니다!",
  ];
  if (!s.english) return ko.join("\n");
  return [
    ...ko,
    "",
    "Hello! I'd like to book a family massage.",
    `- Date/Time: Sun, Oct 4, ${time}`,
    "- 2 adults: Hot Stone & Aroma 90 min",
    "- 1 child (4 years old): Kids body massage",
    "- One room with 3 beds for the three of us, please",
    "- Name: ○○○",
    "Please let me know the total price. Thank you!",
  ].join("\n");
}

